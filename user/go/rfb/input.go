package rfb

// KeysymToHID maps the numeric X11 keysyms used by RFB to USB HID keyboard
// page 0x07 usages. It returns false for keys that have no known physical
// usage; in particular an unknown keysym must not turn into key 0. Uppercase
// and shifted punctuation map to the same physical key as their base form.
// Modifier state is the caller's seat policy, not a property of a keysym.
func KeysymToHID(k uint32) (uint8, bool) {
	if k >= 'a' && k <= 'z' {
		return uint8(k-'a') + 0x04, true
	}
	if k >= 'A' && k <= 'Z' {
		return uint8(k-'A') + 0x04, true
	}
	if k >= '1' && k <= '9' {
		return uint8(k-'1') + 0x1e, true
	}
	if k == '0' {
		return 0x27, true
	}
	if k >= 0xffbe && k <= 0xffc9 { // F1..F12
		return uint8(k-0xffbe) + 0x3a, true
	}
	if k >= 0xffca && k <= 0xffd5 { // F13..F24
		return uint8(k-0xffca) + 0x68, true
	}
	u, ok := keysymUsages[k]
	return u, ok
}

// These constants are keysyms (not character codes or HID codes). The table
// deliberately has no X11 package dependency. RFC 6143 §7.5.4 refers to
// the X11 keysym numbers; the HID values are USB keyboard page 0x07.
