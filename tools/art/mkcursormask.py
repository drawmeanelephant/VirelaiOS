#!/usr/bin/env python3
"""mkcursormask.py -- rasterize the delivered cursor set into kernel masks.

The kernel pointer is a 16x24 two-level mask (kernel/src/driving_award.zig):
'.' transparent, '#' the dark outline, 'o' the white fill. The vendored
cursor masters (`design/art/virelai/cursor-*/cursor-*-V*R*@2x.png`,
64x96 = 4x ship) reduce to that mask by 4x4 box sampling: a ship pixel is
'#' when the block's opaque pixels are predominantly dark ink, 'o' when
predominantly light, '.' when the block is mostly transparent.

Usage:
    python3 tools/art/mkcursormask.py             # vendored masters -> MASKS.TXT
    python3 tools/art/mkcursormask.py --arrow     # arrow rows only
    python3 tools/art/mkcursormask.py <png-dir>   # flat <slug>.png dir (legacy)

Masks + the vendored HOTSPOTS.md ship coordinates land in
image/art/cursors/MASKS.TXT for the cursor-shape card; the refreshed
arrow is pasted into kernel/src/driving_award.zig's cursor_mask.
"""

import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SHIP = (16, 24)

# 8.3 share name -> source slug (same mapping as adopt.py's cursor rows).
CURSORS = [
    ("CURS_PTR", "cursor-arrow"),
    ("CURS_TXT", "cursor-ibeam"),
    ("CURS_LNK", "cursor-hand"),
    ("CURS_GRB", "cursor-grab"),
    ("CURS_GRG", "cursor-grabbing"),
    ("CURS_RSX", "cursor-resize-x"),
    ("CURS_RSY", "cursor-resize-y"),
    ("CURS_XHR", "cursor-crosshair"),
    ("CURS_BSY", "cursor-busy"),
    ("CURS_NO",  "cursor-not-allowed"),
]

# design/art/virelai/HOTSPOTS.md ship (16x24) coordinates (f-artcraft #1249).
HOTSPOTS = {
    "CURS_PTR": (1, 1), "CURS_TXT": (8, 12), "CURS_LNK": (6, 2),
    "CURS_GRB": (8, 14), "CURS_GRG": (8, 14), "CURS_RSX": (8, 12),
    "CURS_RSY": (8, 12), "CURS_XHR": (8, 12), "CURS_BSY": (8, 12),
    "CURS_NO": (8, 12),
}


def mask_rows(img: Image.Image):
    img = img.convert("RGBA").resize(SHIP, Image.BOX)
    rows = []
    for y in range(SHIP[1]):
        row = []
        for x in range(SHIP[0]):
            r, g, b, a = img.getpixel((x, y))
            if a < 64:
                row.append(".")
            elif (r + g + b) // 3 < 128:
                row.append("#")
            else:
                row.append("o")
        rows.append("".join(row))
    return rows


def master(slug):
    """The vendored master's highest-revision @2x.png."""
    d = ROOT / "design" / "art" / "virelai" / slug
    best = None
    for p in d.glob(f"{slug}-V*R*@2x.png"):
        m = re.fullmatch(rf"{re.escape(slug)}-V(\d+)R(\d+)@2x\.png", p.name)
        if m and (best is None or (m.group(1), m.group(2)) > best[0]):
            best = ((m.group(1), m.group(2)), p)
    if best is None:
        sys.exit(f"mkcursormask: no vendored master under {d}")
    return best[1]


def main():
    args = [a for a in sys.argv[1:] if a != "--arrow"]
    arrow_only = "--arrow" in sys.argv[1:]
    srcdir = Path(args[0]) if args else None

    out = [
        "# Kernel cursor masks generated by tools/art/mkcursormask.py from the",
        "# vendored f-artcraft #1249 masters; hotspots are the delivered ship",
        "# coords (design/art/virelai/HOTSPOTS.md). '#' outline, 'o' fill, '.' transparent.",
    ]
    for name, slug in CURSORS:
        src = srcdir / f"{slug}.png" if srcdir else master(slug)
        if not src.exists():
            sys.exit(f"mkcursormask: missing {src}")
        rows = mask_rows(Image.open(src))
        if arrow_only and name == "CURS_PTR":
            print("\n".join(f'    "{r}",' for r in rows))
            return
        hx, hy = HOTSPOTS[name]
        out += [f"", f"[{name}] hotspot={hx},{hy}"]
        out += rows
    dst = ROOT / "image/art/cursors/MASKS.TXT"
    dst.write_text("\n".join(out) + "\n")
    print(f"mkcursormask: wrote {dst}")


if __name__ == "__main__":
    main()
